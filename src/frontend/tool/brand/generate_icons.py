"""Generate every Rumpun app icon from one geometric definition.

The mark is the one the app already draws on its splash and sign-in screens
(MiniBranchPainter in lib/main.dart): a single trunk with two side branches,
each ending in a leaf, per the identity motif in DESIGN.md. Keeping the icon on
the same geometry means the launcher, the notification, and the first screen
all show one mark. Change both together.

Android icons are written as vector drawables, so they stay sharp at every
density. PNGs are rasterised only for platforms that need bitmaps (legacy
Android launchers, iOS, macOS) and for the reviewable SVG masters.

Run from src/frontend:
    python -m venv /tmp/iconenv && /tmp/iconenv/bin/pip install cairosvg pillow
    /tmp/iconenv/bin/python tool/brand/generate_icons.py
"""

import json
from pathlib import Path

FOREST = "#234B38"
PAPER = "#F7F1E7"

# Geometry copied from MiniBranchPainter, drawn on a 42 unit tile.
TILE = 42
STROKES = (
    "M12,35 Q19,24 19,9",
    "M18,22 Q28,20 32,13",
    "M18,28 Q10,25 8,19",
)
STROKE_WIDTH = 2.0
# (left, top, width, height) of each leaf, as in drawOval.
LEAVES = ((27, 8, 8, 5), (5, 15, 8, 5), (16, 6, 6, 8))
# Centre of the mark's drawn extent, so it can be centred on any canvas.
MARK_CENTRE = (20.0, 21.0)

# Android's adaptive icon canvas. Launchers keep the central 66 unit circle.
CANVAS = 108
LAUNCHER_SCALE = 1.55
# Status bar icons are 24dp and read from alpha only, so the mark fills the
# box and its strokes get heavier to survive the size.
NOTIFICATION_SCALE = 2.2
NOTIFICATION_STROKE = 2.8

HERE = Path(__file__).resolve().parent
FRONTEND = HERE.parents[1]
RES = FRONTEND / "android/app/src/main/res"


def _n(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".")


def _ellipse(left: float, top: float, width: float, height: float) -> str:
    rx, ry = width / 2, height / 2
    cx, cy = left + rx, top + ry
    return (
        f"M{_n(cx - rx)},{_n(cy)} A{_n(rx)},{_n(ry)} 0 1,0 {_n(cx + rx)},{_n(cy)} "
        f"A{_n(rx)},{_n(ry)} 0 1,0 {_n(cx - rx)},{_n(cy)}Z"
    )


def _placement(scale: float) -> tuple[float, float]:
    return CANVAS / 2 - MARK_CENTRE[0] * scale, CANVAS / 2 - MARK_CENTRE[1] * scale


def svg(
    *, colour: str, background: str | None, scale: float, stroke: float = STROKE_WIDTH
) -> str:
    tx, ty = _placement(scale)
    body = "".join(
        f'<path d="{d}" fill="none" stroke="{colour}" stroke-width="{_n(stroke)}" stroke-linecap="round"/>'
        for d in STROKES
    ) + "".join(f'<path d="{_ellipse(*leaf)}" fill="{colour}"/>' for leaf in LEAVES)
    back = (
        f'<rect width="{CANVAS}" height="{CANVAS}" fill="{background}"/>'
        if background
        else ""
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}">{back}'
        f'<g transform="translate({_n(tx)} {_n(ty)}) scale({_n(scale)})">{body}</g></svg>'
    )


def vector_drawable(
    *, colour: str, size_dp: int, scale: float, stroke: float = STROKE_WIDTH
) -> str:
    tx, ty = _placement(scale)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/brand/generate_icons.py. Edit the script, not this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp}dp"',
        f'    android:height="{size_dp}dp"',
        f'    android:viewportWidth="{CANVAS}"',
        f'    android:viewportHeight="{CANVAS}">',
        (
            f'    <group android:translateX="{_n(tx)}" android:translateY="{_n(ty)}"'
            f' android:scaleX="{_n(scale)}" android:scaleY="{_n(scale)}">'
        ),
    ]
    for d in STROKES:
        lines += [
            "        <path",
            f'            android:pathData="{d}"',
            f'            android:strokeColor="{colour}"',
            f'            android:strokeWidth="{_n(stroke)}"',
            '            android:strokeLineCap="round" />',
        ]
    for leaf in LEAVES:
        lines += [
            "        <path",
            f'            android:pathData="{_ellipse(*leaf)}"',
            f'            android:fillColor="{colour}" />',
        ]
    lines += ["    </group>", "</vector>", ""]
    return "\n".join(lines)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def android_vectors() -> None:
    write(
        RES / "drawable/ic_launcher_foreground.xml",
        vector_drawable(colour=PAPER, size_dp=108, scale=LAUNCHER_SCALE),
    )
    # Android 13 themed icons tint this single-colour layer with the wallpaper palette.
    write(
        RES / "drawable/ic_launcher_monochrome.xml",
        vector_drawable(colour="#FFFFFFFF", size_dp=108, scale=LAUNCHER_SCALE),
    )
    write(
        RES / "drawable/ic_stat_rumpun.xml",
        vector_drawable(
            colour="#FFFFFFFF",
            size_dp=24,
            scale=NOTIFICATION_SCALE,
            stroke=NOTIFICATION_STROKE,
        ),
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_icons.py. Edit the script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/rumpun_forest" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    write(RES / "mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    write(
        RES / "values/rumpun_colors.xml",
        "\n".join(
            [
                '<?xml version="1.0" encoding="utf-8"?>',
                "<!-- Generated by tool/brand/generate_icons.py. Palette from DESIGN.md. -->",
                "<resources>",
                f'    <color name="rumpun_paper">{PAPER}</color>',
                f'    <color name="rumpun_forest">{FOREST}</color>',
                "</resources>",
                "",
            ]
        ),
    )


def rasters() -> None:
    import io

    import cairosvg
    from PIL import Image, ImageDraw

    def render(markup: str, size: int) -> Image.Image:
        png = cairosvg.svg2png(
            bytestring=markup.encode(), output_width=size, output_height=size
        )
        return Image.open(io.BytesIO(png)).convert("RGBA")

    # Full-bleed square, used where the platform applies its own mask (iOS).
    square = svg(colour=PAPER, background=FOREST, scale=LAUNCHER_SCALE * 1.3)
    write(HERE / "rumpun_icon.svg", square)

    # Pre-API 26 launchers take a bitmap; a round plate matches most of them.
    legacy = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for density, size in legacy.items():
        image = render(square, size * 4)
        mask = Image.new("L", image.size, 0)
        ImageDraw.Draw(mask).ellipse(
            (0, 0, image.width - 1, image.height - 1), fill=255
        )
        plate = Image.new("RGBA", image.size, (0, 0, 0, 0))
        plate.paste(image, (0, 0), mask)
        plate.resize((size, size), Image.LANCZOS).save(
            RES / f"mipmap-{density}/ic_launcher.png"
        )

    ios = FRONTEND / "ios/Runner/Assets.xcassets/AppIcon.appiconset"
    for entry in json.loads((ios / "Contents.json").read_text())["images"]:
        points = float(entry["size"].split("x")[0])
        scale = int(entry["scale"].rstrip("x"))
        pixels = round(points * scale)
        # App Store icons must not carry transparency.
        render(square, pixels).convert("RGB").save(ios / entry["filename"])

    macos = FRONTEND / "macos/Runner/Assets.xcassets/AppIcon.appiconset"
    for entry in json.loads((macos / "Contents.json").read_text())["images"]:
        points = int(entry["size"].split("x")[0])
        scale = int(entry["scale"].rstrip("x"))
        pixels = points * scale
        # macOS icons sit on a rounded plate inset from the canvas edge.
        big = render(square, 1024)
        inset = 100
        mask = Image.new("L", (1024, 1024), 0)
        ImageDraw.Draw(mask).rounded_rectangle(
            (inset, inset, 1023 - inset, 1023 - inset), radius=185, fill=255
        )
        plate = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
        plate.paste(big, (0, 0), mask)
        plate.resize((pixels, pixels), Image.LANCZOS).save(macos / entry["filename"])


if __name__ == "__main__":
    android_vectors()
    rasters()
