const otherGroup = GroceryGroup('other', 'Lainnya', []);

GroceryGroup groupFor(String text) {
  final value = ' ${text.toLowerCase()} ';
  for (final group in groceryGroups) {
    for (final word in group.words) {
      if (value.contains(word.endsWith(' ') ? ' $word' : word)) return group;
    }
  }
  return otherGroup;
}
